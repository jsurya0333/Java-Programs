package day7;

public class Switchcaseexmpll {

	public static void main(String[] args) {
		String mul="add";
		int a=10;
		int b=20;
		switch (mul) {
		case "add":
			System.out.println(a+b);
			break;
		case "sub":
			System.out.println(a-b);
			break;
		case "mul":
			System.out.println(a*b);
			break;
		case "div":
			System.out.println(a/b);
			break;
		
		}
		
	}

}
